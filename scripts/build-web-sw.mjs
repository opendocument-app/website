/*
  Writes `dist/web-sw.js`, the service worker of the web app at `/web`, after
  `astro build`. Run by `postbuild`.

  The worker needs the list of files that make one build of the app, and the
  names of the scripts change with every build, so only the build output can
  give that list. The script puts the list and a version in front of the
  template `scripts/web-sw.js`.

  The version is a hash of the contents of the files on the list. So a build
  that changes nothing in the app makes the same worker, and the browser does
  not download the app again for it.
*/
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');

async function filesIn(dir) {
  const entries = await readdir(dir, { withFileTypes: true, recursive: true });
  return entries
    .filter((e) => e.isFile())
    .map((e) => join(e.parentPath, e.name));
}

const { version: odrVersion } = JSON.parse(
  await readFile(join(root, 'node_modules/@opendocument/odr-core/package.json'), 'utf8'),
);

const files = [
  join(dist, 'web.html'),
  join(dist, 'web.webmanifest'),
  join(dist, 'favicon.svg'),
  join(dist, 'icon-192.png'),
  join(dist, 'icon-512.png'),
  join(dist, 'icon-maskable-512.png'),
  ...(await filesIn(join(dist, '_astro'))),
  // The type declarations are for developers, not for the page.
  ...(await filesIn(join(dist, 'odr', odrVersion))).filter((f) => !f.endsWith('.d.ts')),
].sort();

const hash = createHash('sha256');
const precache = [];
for (const file of files) {
  const path = '/' + relative(dist, file).split(sep).join('/');
  // Firebase serves `web.html` at `/web` (`cleanUrls`), and the manifest
  // starts the app at `/web`.
  const url = path === '/web.html' ? '/web' : path;
  precache.push(url);
  hash.update(url).update(await readFile(file));
}

const version = hash.digest('hex').slice(0, 16);
const template = await readFile(join(root, 'scripts/web-sw.js'), 'utf8');
await writeFile(
  join(dist, 'web-sw.js'),
  `/* Generated by scripts/build-web-sw.mjs from scripts/web-sw.js. */\n` +
    `const VERSION = ${JSON.stringify(version)};\n` +
    `const PRECACHE = ${JSON.stringify(precache, null, 2)};\n\n` +
    template,
);

console.log(`web-sw.js ${version}: ${precache.length} files in the cache of the web app`);
